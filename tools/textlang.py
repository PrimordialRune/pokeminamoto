#!/usr/bin/env python3
"""Per-language map text: text.<lang>.pory files next to a map's scripts.pory.

A map keeps its logic in scripts.pory and its dialogue in text.en.pory, a file
of Poryscript `text Name { ... }` blocks and nothing else. A translation is
text.it.pory (fr, de, es...) with the same block names. The build picks one
language (make LANGUAGE=ITALIAN) and compiles one text.inc per map:

  merge DIR LANG -o OUT   write the blocks of DIR/text.en.pory in order, each
                          taken from DIR/text.LANG.pory when it has it (the
                          English block stays as a fallback otherwise)
  check                   list, for every map, the blocks a translation is
                          missing, the ones it has that English doesn't, and
                          duplicates (tools/check_data.py runs this too)

See docs/engineering/map-text.md.
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# make LANGUAGE=... -> file suffix
LANGUAGE_CODES = {
    "ENGLISH": "en",
    "ITALIAN": "it",
    "FRENCH": "fr",
    "GERMAN": "de",
    "SPANISH": "es",
    "JAPANESE": "ja",
}


class TextFileError(Exception):
    pass


def parse_blocks(path):
    """[(name, source of the whole `text Name { ... }` block)] in file order."""
    src = open(path, encoding="utf-8").read()
    blocks, i, n = [], 0, len(src)

    def skip_space_and_comments(i):
        while i < n:
            if src[i].isspace():
                i += 1
            elif src.startswith("//", i):
                j = src.find("\n", i)
                i = n if j < 0 else j + 1
            elif src.startswith("/*", i):
                j = src.find("*/", i + 2)
                if j < 0:
                    raise TextFileError(f"{path}: unterminated /* comment")
                i = j + 2
            else:
                break
        return i

    while True:
        i = skip_space_and_comments(i)
        if i >= n:
            return blocks
        m = re.compile(r"text\s+(\w+)\s*\{").match(src, i)
        if not m:
            line = src.count("\n", 0, i) + 1
            raise TextFileError(f"{path}:{line}: only `text Name {{ ... }}` blocks belong in a text file")
        start, i, depth = i, m.end(), 1
        while depth:
            if i >= n:
                raise TextFileError(f"{path}: block {m.group(1)} is not closed")
            c = src[i]
            if c == '"':
                i += 1
                while i < n and src[i] != '"':
                    i += 2 if src[i] == "\\" else 1
            elif src.startswith("//", i):
                i = src.find("\n", i)
                i = n if i < 0 else i
                continue
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            i += 1
        blocks.append((m.group(1), src[start:i]))


def text_dirs():
    return sorted(os.path.dirname(p) for p in glob.glob(os.path.join(ROOT, "data/maps/*/text.en.pory")))


def merge(directory, lang, out):
    english = parse_blocks(os.path.join(directory, "text.en.pory"))
    translated = {}
    path = os.path.join(directory, f"text.{lang}.pory")
    if lang != "en" and os.path.exists(path):
        translated = dict(parse_blocks(path))
    rel = os.path.relpath(directory, ROOT)
    lines = [f"// Generated by tools/textlang.py from {rel}/text.en.pory"
             + (f" and text.{lang}.pory" if translated else "") + ". Do not edit.\n"]
    for name, block in english:
        if lang != "en" and name not in translated:
            lines.append(f"// {name}: no {lang} translation yet, English kept\n")
        lines.append(translated.get(name, block) + "\n")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def problems():
    """[(kind, message)]: kind is 'missing' (a translation lacks a block) or 'error'."""
    out = []
    for d in text_dirs():
        rel = os.path.relpath(d, ROOT)
        try:
            english = [name for name, _ in parse_blocks(os.path.join(d, "text.en.pory"))]
        except TextFileError as e:
            out.append(("error", str(e)))
            continue
        for name in {x for x in english if english.count(x) > 1}:
            out.append(("error", f"{rel}/text.en.pory: block {name} is defined twice"))
        for path in sorted(glob.glob(os.path.join(d, "text.*.pory"))):
            lang = os.path.basename(path).split(".")[1]
            if lang == "en":
                continue
            prel = os.path.relpath(path, ROOT)
            if lang not in LANGUAGE_CODES.values():
                out.append(("error", f"{prel}: unknown language code {lang}"))
            try:
                names = [name for name, _ in parse_blocks(path)]
            except TextFileError as e:
                out.append(("error", str(e)))
                continue
            for name in sorted({x for x in names if names.count(x) > 1}):
                out.append(("error", f"{prel}: block {name} is defined twice"))
            for name in sorted(set(names) - set(english)):
                out.append(("error", f"{prel}: block {name} is not in text.en.pory (renamed or removed?)"))
            for name in [x for x in english if x not in names]:
                out.append(("missing", f"{prel}: no translation of {name}"))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("merge")
    m.add_argument("dir")
    m.add_argument("lang")
    m.add_argument("-o", "--out", required=True)
    sub.add_parser("check")
    args = ap.parse_args()
    try:
        if args.cmd == "merge":
            merge(args.dir, args.lang, args.out)
            return 0
    except TextFileError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    found = problems()
    for kind, msg in found:
        print(f"{kind}: {msg}")
    print(f"{len(text_dirs())} maps with text files, {sum(k == 'missing' for k, _ in found)} missing translations, "
          f"{sum(k == 'error' for k, _ in found)} errors")
    return 1 if any(k == "error" for k, _ in found) else 0


if __name__ == "__main__":
    sys.exit(main())
