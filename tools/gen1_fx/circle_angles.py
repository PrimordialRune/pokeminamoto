#!/usr/bin/env python3
"""Writes src/data/battle_transition_gen1.h: the angle of every 8x8 screen
tile around the screen centre, for the Gen 1 circle battle transitions.

0 is 3 o'clock and the angle grows counter-clockwise (64 = 12 o'clock,
128 = 9 o'clock, 192 = 6 o'clock), 256 steps per turn. Run it again only if
the screen size changes:  python3 tools/gen1_fx/circle_angles.py
"""
import math
import os

W, H = 30, 20
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
out = os.path.join(ROOT, "src", "data", "battle_transition_gen1.h")
rows = []
for y in range(H):
    vals = []
    for x in range(W):
        dx = x + 0.5 - W / 2
        dy = H / 2 - (y + 0.5)
        a = math.atan2(dy, dx) / (2 * math.pi) * 256
        vals.append(int(a) % 256 if a >= 0 else int(math.floor(a)) % 256)
    rows.append("    " + ", ".join(f"{v:3d}" for v in vals) + ",")
with open(out, "w") as f:
    f.write("// Generated by tools/gen1_fx/circle_angles.py. Do not edit.\n")
    f.write("// Angle of each screen tile around the centre: 0 = 3 o'clock, counter-clockwise, 256 per turn.\n")
    f.write(f"static const u8 sGen1CircleTileAngles[{H}][{W}] =\n{{\n")
    f.write("\n".join("    {" + r.strip().rstrip(",") + "}," for r in rows))
    f.write("\n};\n")
print(out)
