#!/usr/bin/env python3
"""Generate every per-species C table from the species records.

    python3 tools/speciesgen/speciesgen.py [--list] [--check] [--format]

Reads src/data/species/species.txt (the species and their ids) and one
<name>.json record per species, and writes the headers listed in OUTPUTS
(see tools/speciesgen/README.md for the record format). The Makefile runs it;
outputs are only rewritten when their text changes, so an unchanged record set
rebuilds nothing. --list prints the output paths, --check exits 1 if any
output is missing or stale, --format rewrites the records in the canonical
layout (key order, indentation) that editors and tools should write.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from recordfmt import canonical  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'data', 'species')
BANNER = '// Generated by tools/speciesgen/speciesgen.py from src/data/species/. Do not edit.\n'


class RecordError(Exception):
    pass


# ---------------------------------------------------------------- loading
def load():
    order = []
    with open(os.path.join(SRC, 'species.txt'), encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                order.append(line)
    recs = []
    for i, name in enumerate(order):
        path = os.path.join(SRC, name + '.json')
        try:
            with open(path, encoding='utf-8') as f:
                r = json.load(f)
        except (OSError, ValueError) as e:
            raise RecordError('%s: %s' % (path, e))
        if r.get('species', '').lower() != name:
            raise RecordError('%s: "species" must be %s' % (path, name.upper()))
        r['_id'] = i
        recs.append(r)
    if recs[0]['species'] != 'NONE':
        raise RecordError('species.txt must start with none')
    return recs


# What every species before EGG needs (forms after EGG only need graphics)
REQUIRED = ['name', 'nationalDex', 'baseStats', 'types', 'catchRate', 'expYield', 'genderRatio',
            'eggCycles', 'friendship', 'growthRate', 'eggGroups', 'abilities', 'safariZoneFleeRate',
            'bodyColor', 'cry', 'levelUpMoves', 'tmhm', 'tutor', 'pokedex', 'graphics']
REQUIRED_GFX = ['frontPic', 'stillFrontPic', 'backPic', 'palette', 'shinyPalette', 'icon', 'iconPalette',
                'footprint', 'frontCoords', 'backCoords', 'frontAnimFrames', 'frontAnim', 'backAnim']


class DB:
    def __init__(self, recs):
        self.recs = recs
        self.by = {r['species']: r for r in recs}
        if len(self.by) != len(recs):
            raise RecordError('a species is listed twice in species.txt')
        self.egg = self.by['EGG']['_id']          # NUM_SPECIES
        self.species = recs[:self.egg]              # real species (and NONE)
        for r in recs:
            r.setdefault('symbol', ''.join(w.capitalize() for w in r['species'].split('_')))
        for r in self.species[1:]:
            missing = [k for k in REQUIRED if k not in r]
            missing += ['graphics.' + k for k in REQUIRED_GFX if k not in r.get('graphics', {})]
            if missing:
                raise RecordError('%s: missing %s' % (r['species'], ', '.join(missing)))

    def owner(self, rec, field, sub=None):
        """(record that owns the data, its value) following "@SPECIES" links."""
        seen = set()
        while True:
            holder = rec.get(sub, {}) if sub else rec
            v = holder.get(field)
            if isinstance(v, str) and v.startswith('@'):
                if rec['species'] in seen:
                    raise RecordError('%s.%s: "@" loop' % (rec['species'], field))
                seen.add(rec['species'])
                try:
                    rec = self.by[v[1:]]
                except KeyError:
                    raise RecordError('%s.%s: no species %s' % (rec['species'], field, v[1:]))
                continue
            return rec, v

    def symbol(self, rec, field, default_fmt, sub=None):
        """C name of rec's data for field ({"symbol": ...} overrides the default)."""
        own, v = self.owner(rec, field, sub)
        if isinstance(v, dict) and 'symbol' in v:
            return v['symbol']
        return default_fmt % own['symbol']

    def data(self, rec, field, sub=None):
        own, v = self.owner(rec, field, sub)
        if isinstance(v, dict) and 'symbol' in v:
            return v.get('data', v)
        return v

    def owns(self, rec, field, sub=None):
        holder = rec.get(sub, {}) if sub else rec
        v = holder.get(field)
        return v is not None and not (isinstance(v, str) and v.startswith('@'))


def C(name):
    return 'SPECIES_' + name


def cstr(s):
    return '"%s"' % s


# ---------------------------------------------------------------- constants
def gen_species_h(db):
    out = ['#ifndef GUARD_CONSTANTS_SPECIES_H\n#define GUARD_CONSTANTS_SPECIES_H\n\n', BANNER, '\n']
    for r in db.recs:
        out.append('#define %s %d\n' % (C(r['species']), r['_id']))
    out.append('\n#define NUM_SPECIES SPECIES_EGG\n')
    out.append('\n// Helper macro to check if a species is Gen 1\n'
               '#define IS_SPECIES_GEN1(species) ((species) >= SPECIES_BULBASAUR && (species) <= SPECIES_MEW)\n'
               '\n// Maximum Gen 1 species number\n#define SPECIES_GEN1_MAX SPECIES_MEW\n')
    out.append('\n#include "constants/removed_species.h"\n')
    out.append('\n#endif  // GUARD_CONSTANTS_SPECIES_H\n')
    return ''.join(out)


def dex_list(db, field):
    """[(number, species)] sorted by number; numbers must run 1..n with no gaps."""
    nums = sorted((r[field], r['species']) for r in db.recs if field in r)
    for i, (n, c) in enumerate(nums, 1):
        if n != i:
            raise RecordError('%s numbers must run 1..n without gaps or repeats (%s has %d, expected %d)'
                              % (field, c, n, i))
    return nums


def pokedex_flag_count():
    """POKEDEX_FLAG_COUNT from include/global.h: how many dex numbers the save has flags for."""
    with open('include/global.h', encoding='utf-8') as f:
        m = re.search(r'^#define POKEDEX_FLAG_COUNT (\d+)', f.read(), re.M)
    return int(m.group(1)) if m else None


def gen_pokedex_h(db):
    nat = dex_list(db, 'nationalDex')
    reg = dex_list(db, 'dex')
    cap = pokedex_flag_count()
    if cap is not None and len(nat) > cap:
        raise RecordError('%d national dex numbers, but the save only has Pokédex flags for 1..%d '
                          '(POKEDEX_FLAG_COUNT in include/global.h; raising it changes the save layout)'
                          % (len(nat), cap))
    out = ['#ifndef GUARD_CONSTANTS_POKEDEX_H\n#define GUARD_CONSTANTS_POKEDEX_H\n\n', BANNER, '\n']
    out.append('// National Pokédex order\nenum {\n    NATIONAL_DEX_NONE,\n')
    for n, c in nat:
        out.append('    NATIONAL_DEX_%s,\n' % c)
    out.append('};\n\n')
    out.append('#define NATIONAL_DEX_COUNT %d\n' % len(nat))
    out.append('// The original 151 (Bulbasaur to Mew). There are no Johto species: the Johto\n'
               '// range is empty, so the Kanto/Johto/Hoenn completion checks only see Kanto.\n')
    out.append('#define KANTO_DEX_COUNT NATIONAL_DEX_MEW\n#define JOHTO_DEX_COUNT KANTO_DEX_COUNT\n\n')
    out.append('// The regional (Minamoto) Pokédex: the species with a "dex" number in their record\n')
    out.append('#define REGIONAL_DEX_COUNT %d\n' % len(reg))
    out.append('\n#endif // GUARD_CONSTANTS_POKEDEX_H\n')
    return ''.join(out)


# ---------------------------------------------------------------- base stats
GENDER = {'MALE': 'MON_MALE', 'FEMALE': 'MON_FEMALE', 'GENDERLESS': 'MON_GENDERLESS'}
STATS = [('hp', 'baseHP'), ('attack', 'baseAttack'), ('defense', 'baseDefense'),
         ('speed', 'baseSpeed'), ('spAttack', 'baseSpAttack'), ('spDefense', 'baseSpDefense')]
EVS = [('hp', 'evYield_HP'), ('attack', 'evYield_Attack'), ('defense', 'evYield_Defense'),
       ('speed', 'evYield_Speed'), ('spAttack', 'evYield_SpAttack'), ('spDefense', 'evYield_SpDefense')]


def gender(v):
    if isinstance(v, str):
        return GENDER[v]
    return 'PERCENT_FEMALE(%s)' % v


def gen_species_info(db):
    out = [BANNER, '\n// Maximum value for a female Pokémon is 254 (MON_FEMALE) which is 100% female.\n'
           '// 255 (MON_GENDERLESS) is reserved for genderless Pokémon.\n'
           '#define PERCENT_FEMALE(percent) min(254, ((percent * 255) / 100))\n\n'
           'const struct SpeciesInfo gSpeciesInfo[] =\n{\n']
    for r in db.species:
        if 'info' in r and r['info'] is None:
            out.append('    [%s] = {0},\n\n' % C(r['species']))
            continue
        if 'baseStats' not in r:
            continue
        b, ev = r['baseStats'], r.get('evYield', {})
        items = r.get('heldItems', ['NONE', 'NONE'])
        L = ['    [%s] =\n    {\n' % C(r['species'])]
        for k, f in STATS:
            L.append('        .%s = %d,\n' % (f, b[k]))
        L.append('        .types = { %s },\n' % ', '.join('TYPE_' + t for t in r['types']))
        L.append('        .catchRate = %d,\n        .expYield = %d,\n' % (r['catchRate'], r['expYield']))
        for k, f in EVS:
            L.append('        .%s = %d,\n' % (f, ev.get(k, 0)))
        L.append('        .itemCommon = ITEM_%s,\n        .itemRare = ITEM_%s,\n' % tuple(items))
        L.append('        .genderRatio = %s,\n' % gender(r['genderRatio']))
        L.append('        .eggCycles = %d,\n        .friendship = %d,\n' % (r['eggCycles'], r['friendship']))
        L.append('        .growthRate = GROWTH_%s,\n' % r['growthRate'])
        L.append('        .eggGroups = { %s },\n' % ', '.join('EGG_GROUP_' + g for g in r['eggGroups']))
        L.append('        .abilities = { %s },\n' % ', '.join('ABILITY_' + a for a in r['abilities']))
        L.append('        .safariZoneFleeRate = %d,\n' % r['safariZoneFleeRate'])
        L.append('        .bodyColor = BODY_COLOR_%s,\n' % r['bodyColor'])
        L.append('        .noFlip = %s,\n' % ('TRUE' if r.get('noFlip') else 'FALSE'))
        L.append('    },\n\n')
        out += L
    out.append('};\n')
    return ''.join(out)


def gen_species_names(db):
    out = [BANNER, 'const u8 gSpeciesNames[][POKEMON_NAME_LENGTH + 1] = {\n']
    for r in db.species:
        if 'name' in r:
            if len(r['name']) > 10 and '{' not in r['name']:
                raise RecordError('%s: name longer than 10 characters' % r['species'])
            out.append('    [%s] = _(%s),\n' % (C(r['species']), cstr(r['name'])))
    out.append('};\n')
    return ''.join(out)


# ---------------------------------------------------------------- moves
def gen_level_up(db):
    out = [BANNER, '#define LEVEL_UP_MOVE(lvl, move) ((lvl << 9) | move)\n\n']
    for r in db.species:
        if db.owns(r, 'levelUpMoves'):
            out.append('static const u16 %s[] = {\n' % db.symbol(r, 'levelUpMoves', 's%sLevelUpLearnset'))
            for lvl, move in db.data(r, 'levelUpMoves'):
                out.append('    LEVEL_UP_MOVE(%2d, MOVE_%s),\n' % (lvl, move))
            out.append('    LEVEL_UP_END\n};\n\n')
    return ''.join(out)


def gen_level_up_pointers(db):
    out = [BANNER, 'const u16 *const gLevelUpLearnsets[NUM_SPECIES] =\n{\n']
    for r in db.species:
        if 'levelUpMoves' in r:
            out.append('    [%s] = %s,\n' % (C(r['species']), db.symbol(r, 'levelUpMoves', 's%sLevelUpLearnset')))
    out.append('};\n')
    return ''.join(out)


def gen_tmhm(db):
    out = [BANNER, '''/* Expands to:
 * struct TMHMLearnset
 * {
 *     u32 MEGA_PUNCH:1;
 *     ...
 *     u32 CUT:1;
 *     ...
 * }; */
#define TMHM_LEARN(id) u32 id:1;
struct TMHMLearnset
{
    FOREACH_TMHM(TMHM_LEARN)
};
#undef TMHM_LEARN

const union {
    struct TMHMLearnset learnset;
    u32 as_u32s[sizeof(struct TMHMLearnset) / sizeof(u32)];
} gTMHMLearnsets[NUM_SPECIES] =
{
''']
    for r in db.species:
        if 'tmhm' not in r:
            continue
        tms = db.data(r, 'tmhm')
        if not tms:
            out.append('    [%s] = {},\n' % C(r['species']))
        else:
            out.append('    [%s] = { .learnset = {\n' % C(r['species']))
            out += ['        .%s = TRUE,\n' % t for t in tms]
            out.append('    } },\n')
    out.append('};\n')
    return ''.join(out)


def gen_tutor(db):
    out = [BANNER, '// Bits are tutor slots (TUTOR_MOVE_*), not moves: gTutorMoves says what each slot teaches.\n'
           '#define TUTOR(move) (1u << (TUTOR_##move))\n\nstatic const u32 sTutorLearnsets[] =\n{\n']
    for r in db.species:
        if 'tutor' not in r:
            continue
        t = db.data(r, 'tutor')
        expr = ' | '.join('TUTOR(MOVE_%s)' % m for m in t) if t else '0'
        out.append('    [%s] = (%s),\n' % (C(r['species']), expr))
    out.append('};\n')
    return ''.join(out)


def gen_egg_moves(db):
    out = [BANNER, '#define EGG_MOVES_SPECIES_OFFSET 20000\n#define EGG_MOVES_TERMINATOR 0xFFFF\n'
           '#define egg_moves(species, moves...) (SPECIES_##species + EGG_MOVES_SPECIES_OFFSET), moves\n\n'
           'const u16 gEggMoves[] = {\n']
    for r in db.species:
        if r.get('eggMoves'):
            out.append('    egg_moves(%s,\n%s),\n\n' % (r['species'], ',\n'.join(
                '              MOVE_' + m for m in db.data(r, 'eggMoves'))))
    out.append('    EGG_MOVES_TERMINATOR\n};\n')
    return ''.join(out)


def gen_evolution(db):
    out = [BANNER, 'const struct Evolution gEvolutionTable[NUM_SPECIES][EVOS_PER_MON] =\n{\n']
    for r in db.species:
        evos = r.get('evolutions')
        if not evos:
            continue
        parts = []
        for e in evos:
            p = e['param']
            if isinstance(p, str):
                p = 'ITEM_' + p
            if e['into'] not in db.by:
                raise RecordError('%s: evolves into unknown species %s' % (r['species'], e['into']))
            parts.append('{EVO_%s, %s, %s}' % (e['method'], p, C(e['into'])))
        out.append('    [%s] = {%s},\n' % (C(r['species']), ', '.join(parts)))
    out.append('};\n')
    return ''.join(out)


# ---------------------------------------------------------------- pokedex
def by_national(db):
    return sorted((r for r in db.recs if 'pokedex' in r),
                  key=lambda r: 0 if r['species'] == 'NONE' else r['nationalDex'])


def dex_name(r):
    return 'NATIONAL_DEX_' + r['species']


def gen_pokedex_text(db):
    out = [BANNER]
    for r in by_national(db):
        if db.owns(r, 'text', 'pokedex'):
            lines = db.data(r, 'text', 'pokedex')
            body = '\n'.join('    "%s%s"' % (l, '\\n' if i < len(lines) - 1 else '') for i, l in enumerate(lines))
            out.append('const u8 %s[] = _(\n%s);\n\n' % (db.symbol(r, 'text', 'g%sPokedexText', 'pokedex'), body))
    return ''.join(out)


def gen_pokedex_entries(db):
    out = [BANNER, 'const struct PokedexEntry gPokedexEntries[] =\n{\n']
    for r in by_national(db):
        d = r['pokedex']
        out.append('    [%s] =\n    {\n' % ('NATIONAL_DEX_NONE' if r['species'] == 'NONE' else dex_name(r)))
        out.append('        .categoryName = _(%s),\n' % cstr(d['category']))
        out.append('        .height = %d,\n        .weight = %d,\n' % (d['height'], d['weight']))
        out.append('        .description = %s,\n' % db.symbol(r, 'text', 'g%sPokedexText', 'pokedex'))
        out.append('        .pokemonScale = %d,\n        .pokemonOffset = %d,\n' % (d['pokemonScale'], d['pokemonOffset']))
        out.append('        .trainerScale = %d,\n        .trainerOffset = %d,\n    },\n\n' % (d['trainerScale'], d['trainerOffset']))
    out.append('};\n')
    return ''.join(out)


def dex_orders(db):
    """The Pokedex 'sort by' lists; ties go in National Pokedex order."""
    mons = [r for r in db.recs if r.get('nationalDex') and r['species'] != 'NONE']
    alpha = sorted(mons, key=lambda r: (r['name'], r['nationalDex']))
    weight = sorted((r for r in mons if 'pokedex' in r), key=lambda r: (r['pokedex']['weight'], r['nationalDex']))
    height = sorted((r for r in mons if 'pokedex' in r), key=lambda r: (r['pokedex']['height'], r['nationalDex']))
    return alpha, weight, height


def gen_pokedex_orders(db):
    alpha, weight, height = dex_orders(db)
    out = [BANNER]
    for name, lst in (('gPokedexOrder_Alphabetical', alpha), ('gPokedexOrder_Weight', weight),
                      ('gPokedexOrder_Height', height)):
        out.append('const u16 %s[] =\n{\n' % name)
        out += ['    %s,\n' % dex_name(r) for r in lst]
        out.append('};\n\n')
    return ''.join(out)


def gen_dex_numbers(db):
    out = [BANNER, '// Species -> regional and National Pokédex numbers, and regional -> National.\n'
           '// SPECIES_NONE is left out: index with species - 1.\n']
    for name, field in (('sSpeciesToRegionalPokedexNum', 'dex'), ('sSpeciesToNationalPokedexNum', 'nationalDex')):
        out.append('static const u16 %s[NUM_SPECIES - 1] =\n{\n' % name)
        for r in db.species[1:]:
            if field in r:
                out.append('    [%s - 1] = %d,\n' % (C(r['species']), r[field]))
        out.append('};\n\n')
    out.append('static const u16 sRegionalToNationalOrder[REGIONAL_DEX_COUNT] =\n{\n')
    for n, c in dex_list(db, 'dex'):
        if 'nationalDex' not in db.by[c]:
            raise RecordError('%s: has a regional "dex" number but no "nationalDex"' % c)
        out.append('    [%d - 1] = NATIONAL_DEX_%s,\n' % (n, c))
    out.append('};\n')
    return ''.join(out)


def cry_owners(db):
    """(species, Cry_ symbol, sample path) for every species after NONE, in id order."""
    out = []
    for r in db.species[1:]:
        if 'cry' not in r:
            raise RecordError('%s: no "cry"' % r['species'])
        out.append((r, db.symbol(r, 'cry', 'Cry_%s'), db.data(r, 'cry')))
    return out


def gen_cry_tables(db):
    # Cry ids are species - 1 (SpeciesToCryId); the reversed table plays cries backwards
    out = ['@ ' + BANNER[3:], '\t.align 2\ngCryTable::\n']
    cries = cry_owners(db)
    out += ['\tcry %s\n' % sym for r, sym, path in cries]
    out.append('\n\t.align 2\ngCryTable_Reverse::\n')
    out += ['\tcry_reverse %s\n' % sym for r, sym, path in cries]
    return ''.join(out)


def gen_cry_samples(db):
    out, done = ['@ ' + BANNER[3:]], set()
    for r, sym, path in cry_owners(db):
        if db.owns(r, 'cry') and sym not in done:
            done.add(sym)
            out.append('\n\t.align 2\n%s::\n\t.incbin "%s"\n' % (sym, path))
    return ''.join(out)


# ---------------------------------------------------------------- animations
def gfx(r):
    return r.get('graphics', {})


def gen_front_anim_ids(db):
    out = [BANNER, '// SPECIES_NONE is left out of these two tables: index with species - 1.\n\n'
           'static const u8 sMonFrontAnimIdsTable[NUM_SPECIES - 1] =\n{\n']
    for r in db.species[1:]:
        if 'frontAnim' in gfx(r):
            out.append('    [%s - 1] = ANIM_%s,\n' % (C(r['species']), gfx(r)['frontAnim']))
    out.append('};\n\nstatic const u8 sMonAnimationDelayTable[NUM_SPECIES - 1] =\n{\n')
    for r in db.species[1:]:
        if gfx(r).get('frontAnimDelay'):
            out.append('    [%s - 1] = %d,\n' % (C(r['species']), gfx(r)['frontAnimDelay']))
    out.append('};\n')
    return ''.join(out)


def gen_back_anim_ids(db):
    out = [BANNER, 'static const u8 sSpeciesToBackAnimSet[] =\n{\n']
    for r in db.species:
        if 'backAnim' in gfx(r):
            out.append('    [%s] = BACK_ANIM_%s,\n' % (C(r['species']), gfx(r)['backAnim']))
    out.append('};\n')
    return ''.join(out)


def gen_front_pic_anims(db):
    out = [BANNER]
    tables = []
    for r in db.recs:
        if not db.owns(r, 'frontAnimFrames', 'graphics'):
            continue
        g, sym = gfx(r), r['symbol']
        names = []
        for i, frames in enumerate(g['frontAnimFrames'], 0 if g.get('frontAnimFrame0') else 1):
            n = 'sAnim_%s_%d' % (sym, i)
            names.append(n)
            out.append('static const union AnimCmd %s[] =\n{\n' % n)
            out += ['    ANIMCMD_FRAME(%d, %d),\n' % (a, b) for a, b in frames]
            out.append('    ANIMCMD_END,\n};\n\n')
        if not g.get('frontAnimFrame0'):
            names.insert(0, 'sAnim_GeneralFrame0')
        tables.append('static const union AnimCmd *const sAnims_%s[] =\n{\n%s};\n\n'
                      % (sym, ''.join('    %s,\n' % n for n in names)))
    out += tables
    out.append('const union AnimCmd *const *const gMonFrontAnimsPtrTable[] =\n{\n')
    for r in db.recs:
        if 'frontAnimFrames' in gfx(r):
            own, _ = db.owner(r, 'frontAnimFrames', 'graphics')
            out.append('    [%s] = sAnims_%s,\n' % (C(r['species']), own['symbol']))
    out.append('};\n')
    return ''.join(out)


# ---------------------------------------------------------------- graphics
# field: (C prefix, C type, table)
GFX = {
    'frontPic': ('gMonFrontPic_', 'u32'),
    'stillFrontPic': ('gMonStillFrontPic_', 'u32'),
    'backPic': ('gMonBackPic_', 'u32'),
    'palette': ('gMonPalette_', 'u32'),
    'shinyPalette': ('gMonShinyPalette_', 'u32'),
    'icon': ('gMonIcon_', 'u8'),
    'footprint': ('gMonFootprint_', 'u8'),
}


def gfx_sym(db, r, field):
    return db.symbol(r, field, GFX[field][0] + '%s', 'graphics')


def gfx_path(db, r, field):
    return db.data(r, field, 'graphics')


def incbins(db, fields):
    out, done = [], {}
    for r in db.recs:
        block = []
        for f in fields:
            if db.owns(r, f, 'graphics'):
                t, sym, path = GFX[f][1], gfx_sym(db, r, f), gfx_path(db, r, f)
                if sym in done:
                    # one file used for two pics, e.g. the Egg's back pic is its front pic
                    if done[sym] != (t, path):
                        raise RecordError('%s: %s is defined twice with different files' % (r['species'], sym))
                    continue
                done[sym] = (t, path)
                block.append('const %s %s[] = INCBIN_%s("%s");\n' % (t, sym, t.upper(), path))
        if block:
            out += block + ['\n']
    return out


def gen_gfx_incbins(db):
    return ''.join([BANNER] + incbins(db, ['stillFrontPic', 'palette', 'backPic', 'shinyPalette', 'icon', 'footprint']))


def gen_anim_front_incbins(db):
    return ''.join([BANNER] + incbins(db, ['frontPic']))


def externs(db, fields):
    seen, out = set(), []
    for r in db.recs:
        for f in fields:
            if f in gfx(r):
                s = gfx_sym(db, r, f)
                if s not in seen:
                    seen.add(s)
                    out.append('extern const %s %s[];\n' % (GFX[f][1], s))
    return out + ['\n']


def gen_sprite_table(field, table, macro):
    def gen(db):
        out = [BANNER] + externs(db, [field])
        kind = 'CompressedSpritePalette' if 'Palette' in table else 'CompressedSpriteSheet'
        out.append('const struct %s %s[] =\n{\n' % (kind, table))
        for r in db.recs:
            if field in gfx(r):
                out.append('    %s(%s, %s),\n' % (macro, r['species'], gfx_sym(db, r, field)))
        out.append('};\n')
        return ''.join(out)
    return gen


def gen_coords(field, table):
    def gen(db):
        out = [BANNER, '// All Pokémon pics are 64x64, but this data table defines where in this 64x64 frame\n'
               '// the sprite\'s non-transparent pixels actually are.\n'
               '// .size is the dimensions of this drawn pixel area.\n'
               '// .y_offset is the number of pixels between the drawn pixel area and the bottom edge.\n'
               'const struct MonCoords %s[] =\n{\n' % table]
        for r in db.recs:
            if field in gfx(r):
                w, h, y = gfx(r)[field]
                out.append('    [%s] = { .size = MON_COORDS_SIZE(%d, %d), .y_offset = %d },\n' % (C(r['species']), w, h, y))
        out.append('};\n')
        return ''.join(out)
    return gen


def gen_elevation(db):
    out = [BANNER, '// This determines how much higher above the usual position the enemy Pokémon\n'
           '// is during battle. Species that float or fly have nonzero values.\n'
           'const u8 gEnemyMonElevation[NUM_SPECIES] =\n{\n']
    for r in db.species:
        if gfx(r).get('elevation'):
            out.append('    [%s] = %d,\n' % (C(r['species']), gfx(r)['elevation']))
    out.append('};\n')
    return ''.join(out)


def gen_footprints(db):
    out = [BANNER] + externs(db, ['footprint'])
    out.append('const u8 *const gMonFootprintTable[] =\n{\n')
    for r in db.recs:
        if 'footprint' in gfx(r):
            out.append('    [%s] = %s,\n' % (C(r['species']), gfx_sym(db, r, 'footprint')))
    out.append('};\n')
    return ''.join(out)


def gen_icons(db):
    out = [BANNER] + externs(db, ['icon'])
    out.append('const u8 *const gMonIconTable[] =\n{\n')
    for r in db.recs:
        if 'icon' in gfx(r):
            out.append('    [%s] = %s,\n' % (C(r['species']), gfx_sym(db, r, 'icon')))
    out.append('};\n\nconst u8 gMonIconPaletteIndices[] =\n{\n')
    for r in db.recs:
        if 'iconPalette' in gfx(r):
            out.append('    [%s] = %d,\n' % (C(r['species']), gfx(r)['iconPalette']))
    out.append('};\n')
    return ''.join(out)


